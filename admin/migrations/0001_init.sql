-- One row per page load. Duration and scroll depth are updated in place by
-- ping/leave beacons, so a page view stays a single row.
CREATE TABLE pageviews (
  id TEXT PRIMARY KEY,            -- generated by the tracker per page load
  session_id TEXT NOT NULL,
  visitor_id TEXT NOT NULL,       -- daily-salted hash of IP + UA, rotates every UTC day
  ts INTEGER NOT NULL,            -- epoch ms of the page load
  last_seen INTEGER NOT NULL,     -- epoch ms of the latest beacon
  path TEXT NOT NULL,
  title TEXT,
  referrer TEXT,                  -- external referrer only (origin + path)
  ref_host TEXT,
  utm_source TEXT,
  utm_medium TEXT,
  utm_campaign TEXT,
  country TEXT,
  region TEXT,
  city TEXT,
  latitude REAL,
  longitude REAL,
  timezone TEXT,
  as_org TEXT,
  browser TEXT,
  browser_version TEXT,
  os TEXT,
  os_version TEXT,
  device TEXT,                    -- desktop | mobile | tablet | other
  screen TEXT,
  language TEXT,
  duration_ms INTEGER NOT NULL DEFAULT 0,  -- active (visible, non-idle) time
  scroll_pct INTEGER NOT NULL DEFAULT 0,
  visible INTEGER NOT NULL DEFAULT 1       -- 0 after a leave beacon, 1 again on the next ping
);

CREATE INDEX pageviews_ts ON pageviews (ts);
CREATE INDEX pageviews_last_seen ON pageviews (last_seen);
CREATE INDEX pageviews_visitor ON pageviews (visitor_id, last_seen);
CREATE INDEX pageviews_session ON pageviews (session_id, ts);

-- Interactions inside a page view: clicks, outbound links, downloads, copies.
CREATE TABLE events (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  pageview_id TEXT NOT NULL REFERENCES pageviews (id) ON DELETE CASCADE,
  ts INTEGER NOT NULL,
  type TEXT NOT NULL,
  path TEXT NOT NULL,
  label TEXT,
  target TEXT
);

CREATE INDEX events_ts ON events (ts);
CREATE INDEX events_pageview ON events (pageview_id);
CREATE INDEX events_type_ts ON events (type, ts);

-- Random salt per UTC day for visitor hashing. Old salts are deleted so past
-- visitor ids can't be recomputed from an IP address.
CREATE TABLE salts (
  day TEXT PRIMARY KEY,
  salt TEXT NOT NULL
);
